/**
 * Clean project slug for package.json and filenames
 */
function cleanSlug(name?: string): string {
  if (!name) return "my-app";
  return name
    .toLowerCase()
    .replace(/[^a-z0-9_-]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "") || "my-app";
}

/**
 * Extracts Prisma models and generates clean TypeScript interfaces (src/types/index.ts).
 */
export function generateTypeScriptContracts(options: ProjectScaffoldOptions): string {
  const schema = options.prismaSchema || "";
  const models: string[] = [];

  const modelRegex = /model\s+([A-Za-z0-9_]+)\s*\{([^}]+)\}/g;
  let match;
  while ((match = modelRegex.exec(schema)) !== null) {
    const modelName = match[1];
    const body = match[2];
    const fields: string[] = [];

    const lines = body.split("\n");
    for (const rawLine of lines) {
      const line = rawLine.trim();
      if (!line || line.startsWith("//") || line.startsWith("@@")) continue;
      const parts = line.split(/\s+/);
      if (parts.length >= 2) {
        const fieldName = parts[0];
        let fieldType = parts[1];
        const isOptional = fieldType.endsWith("?");
        if (isOptional) fieldType = fieldType.slice(0, -1);
        const isArray = fieldType.endsWith("[]");
        if (isArray) fieldType = fieldType.slice(0, -2);

        let tsType = "string";
        if (fieldType === "Int" || fieldType === "Float") tsType = "number";
        else if (fieldType === "Boolean") tsType = "boolean";
        else if (fieldType === "DateTime") tsType = "string | Date";
        else if (fieldType === "Json") tsType = "Record<string, unknown>";
        else if (["String", "Role", "ProjectStatus", "Status"].includes(fieldType)) tsType = "string";
        else tsType = fieldType;

        const finalType = isArray ? `${tsType}[]` : tsType;
        fields.push(`  ${fieldName}${isOptional ? "?" : ""}: ${finalType};`);
      }
    }

    if (fields.length > 0) {
      models.push(`export interface ${modelName} {\n${fields.join("\n")}\n}`);
    }
  }

  const fallbackTypes = `export interface Feedback {
  id: string;
  title: string;
  description?: string;
  status: "PENDING" | "IN_PROGRESS" | "COMPLETED";
  votes: number;
  createdAt: string;
}

export interface User {
  id: string;
  name?: string;
  email: string;
  role: "USER" | "ADMIN";
}`;

  return `// Standard TypeScript Data Contracts & Interfaces
// Auto-generated by Agentic Architect from Prisma Database Schema

${models.length > 0 ? models.join("\n\n") : fallbackTypes}

export interface ApiResponse<T = unknown> {
  success: boolean;
  data?: T;
  error?: {
    code: string;
    message: string;
  };
}
`;
}

